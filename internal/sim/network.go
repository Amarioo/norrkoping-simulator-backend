// NetworkMeta is what the simulation reads of the importer's notes on the map.
type NetworkMeta struct {
	// Clip is the outline of the mapped area in scene coordinates (x, z), closed.
	Clip [][]float64 `json:"clip"`
}

type TransportNetwork struct {
	Meta          NetworkMeta    `json:"meta"`
	Nodes         []RoadNode     `json:"nodes"`
	Edges         []RoadEdge     `json:"edges"`
	Airports      []Airport      `json:"airports"`
	Airways       []Airway       `json:"airways"`
	TransitRoutes []TransitRoute `json:"transitRoutes"`

	// Outgoing lists the edges leaving each node, in edge order.
	Outgoing [][]int `json:"-"`
	// Junctions marks nodes with more than two distinct onward targets.
	Junctions []bool `json:"-"`
}

// NewTransportNetwork builds a network and its derived indexes.
func NewTransportNetwork(nodes []RoadNode, edges []RoadEdge, airports []Airport, airways []Airway, routes []TransitRoute) *TransportNetwork {
	n := &TransportNetwork{Nodes: nodes, Edges: edges, Airports: airports, Airways: airways, TransitRoutes: routes}
	n.index()
	return n
}

func (n *TransportNetwork) index() {
	n.Outgoing = make([][]int, len(n.Nodes))
	for i, e := range n.Edges {
		n.Outgoing[e.From] = append(n.Outgoing[e.From], i)
	}
	n.Junctions = make([]bool, len(n.Nodes))
	for node, out := range n.Outgoing {
		targets := map[int]bool{}
		for _, e := range out {
			targets[n.Edges[e].To] = true
		}
		n.Junctions[node] = len(targets) > 2
	}
}

// BundledNetwork is the road, rail and airport network shipped in the binary, decoded on first use.
var BundledNetwork = sync.OnceValue(func() *TransportNetwork {
	var n TransportNetwork
	mustDecodeResource("transport-network.json", &n)
	n.index()
	return &n
})

// AccessRecord is one bus access correction to the importer's class heuristic, keyed by OSM way. Basis
// is `osm-tag` / `osm-tag-deny` (explicit bus/psv tags) or `verified-service` (way used by a bus service
// verified against current operator data).
type AccessRecord struct {
	Way   int64  `json:"way"`
	Bus   bool   `json:"bus"`
	Basis string `json:"basis"`
}

// Turnaround is a mapped turnaround facility (OSM highway=turning_circle|turning_loop node).
type Turnaround struct {
	Node int64 `json:"node"`
}

// RoadAccess holds data-driven road policy inputs for the bundled graph, with provenance in
// road-access.json (generated by the UI's scripts/step61b/build-road-access.mjs). Neither part changes
// graph geometry or topology, and entries for ways/nodes absent from a network have no effect.
type RoadAccess struct {
	Records     []AccessRecord `json:"records"`
	Turnarounds []Turnaround   `json:"turnarounds"`
}

// NoRoadAccess applies no corrections.
var NoRoadAccess = &RoadAccess{}

func (a *RoadAccess) busWays() map[int64]bool {
	ways := make(map[int64]bool, len(a.Records))
	for _, r := range a.Records {
		ways[r.Way] = r.Bus
	}
	return ways
}

// TurnaroundNodes marks the network's nodes where reversing is a lawful turning movement.
func (a *RoadAccess) TurnaroundNodes(n *TransportNetwork) []bool {
	wanted := make(map[int64]bool, len(a.Turnarounds))
	for _, t := range a.Turnarounds {
		wanted[t.Node] = true
	}
	nodes := make([]bool, len(n.Nodes))
	for i := range n.Nodes {
		nodes[i] = wanted[n.Nodes[i].ID]
	}
	return nodes
}

var BundledRoadAccess = sync.OnceValue(func() *RoadAccess {
	var a RoadAccess
	mustDecodeResource("road-access.json", &a)
	return &a
})

// EdgeSet is a set of edge indexes that keeps the order they were listed in.
type EdgeSet struct {
	List []int
	has  []bool
}

func newEdgeSet(edges int, list []int) *EdgeSet {
	s := &EdgeSet{List: list, has: make([]bool, edges)}
	for _, e := range list {
		s.has[e] = true
	}
	return s
}

func (s *EdgeSet) Has(edge int) bool { return edge >= 0 && edge < len(s.has) && s.has[edge] }

// policyEdges are the edges a vehicle class may traverse: the importer's truck/bus flags, with bus flags
// corrected by access. Cars use every drivable edge. Through-route pruning runs on this set.
func policyEdges(n *TransportNetwork, kind string, access *RoadAccess) []int {
	busWays := access.busWays()
	edges := make([]int, 0, len(n.Edges))
	for i := range n.Edges {
		e := &n.Edges[i]
		allowed := true
		switch kind {
		case "truck":
			allowed = e.Truck
		case "bus":
			if corrected, ok := busWays[e.Way]; ok {
				allowed = corrected
			} else {
				allowed = e.Bus
			}
		}
		if allowed {
			edges = append(edges, i)
		}
	}
	return edges
}

// throughRoadEdges returns the edges from which roaming traffic can continue without a policy-induced
// U-turn. A bidirectional branch cut off by truck/bus filters is NOT a usable directed cycle. Pruning
// nodes with zero outgoing edges alone misses it. Legitimate termini keep their turnaround behavior: a
// real mapped road end (no other target in the full graph) and a mapped turnaround facility in terminals
// (a driveway beyond a turning circle does not make reversing there artificial). Elsewhere, an onward
// link present in the full graph but unavailable to this policy is a trap and is propagated back.
// Counts are per destination (parallel OSM ways must not masquerade as different exits).
// O(nodes + edges), once per vehicle policy; no graph search in tick/fillPath.
func throughRoadEdges(n *TransportNetwork, candidates []int, terminals []bool) []int {
	exits := make([]map[int]int, len(n.Nodes))
	incoming := make([][]int, len(n.Nodes))
	alive := make([]bool, len(n.Edges))
	for _, id := range candidates {
		e := &n.Edges[id]
		if exits[e.From] == nil {
			exits[e.From] = map[int]int{}
		}
		exits[e.From][e.To]++
		incoming[e.To] = append(incoming[e.To], id)
		alive[id] = true
	}
	var queue []int
	inspect := func(node int) {
		targets := exits[node]
		if len(targets) > 1 {
			return
		}
		only, hasOnly := -1, false
		for target := range targets {
			only, hasOnly = target, true
		}
		// A true road end or turnaround facility is a legitimate turnaround. At a policy boundary, or a
		// branch leading to one, the full map has another exit: propagate its unavailability back.
		if hasOnly {
			realEnd := true
			for _, e := range n.Outgoing[node] {
				if n.Edges[e].To != only {
					realEnd = false
					break
				}
			}
			if realEnd || (terminals != nil && terminals[node]) {
				return
			}
		}
		for _, id := range incoming[node] {
			if !hasOnly || n.Edges[id].From == only {
				queue = append(queue, id)
			}
		}
	}
	for node := range n.Nodes {
		inspect(node)
	}
	for head := 0; head < len(queue); head++ {
		id := queue[head]
		if !alive[id] {
			continue
		}
		alive[id] = false
		e := &n.Edges[id]
		targets := exits[e.From]
		if targets[e.To]--; targets[e.To] == 0 {
			delete(targets, e.To)
			inspect(e.From)
		}
	}
	through := make([]int, 0, len(candidates))
	for _, id := range candidates {
		if alive[id] {
			through = append(through, id)
			alive[id] = false // a candidate listed twice counts once
		}
	}
	return through
}

var roadKinds = []string{"compact", "estate", "truck", "bus"}

// roadPolicies returns the allowed edges for every road vehicle class: access policy, then through-route
// pruning.
func roadPolicies(n *TransportNetwork, access *RoadAccess) map[string]*EdgeSet {
	terminals := access.TurnaroundNodes(n)
	policies := map[string]*EdgeSet{}
	for _, kind := range roadKinds {
		candidates := policyEdges(n, kind, access)
		// Tiny standalone/test networks can have no through route at all; retain their finite-route
		// behavior. The bundled city has thousands of through edges for every supported kind.
		through := throughRoadEdges(n, candidates, terminals)
		if len(through) == 0 {
			through = candidates
		}
		policies[kind] = newEdgeSet(len(n.Edges), through)
	}
	return policies
}
