type RoadNode struct {
	ID               int64
	X, Z, Y          float64
	Signal           bool
	SignalHorizontal *bool
	BusStop          *string
}

func (n *RoadNode) UnmarshalJSON(raw []byte) error {
	var v struct {
		ID               int64    `json:"id"`
		X                float64  `json:"x"`
		Z                float64  `json:"z"`
		Y                *float64 `json:"y"`
		Signal           bool     `json:"signal"`
		SignalHorizontal *bool    `json:"signalHorizontal"`
		BusStop          *string  `json:"busStop"`
	}
	if err := json.Unmarshal(raw, &v); err != nil {
		return err
	}
	*n = RoadNode{ID: v.ID, X: v.X, Z: v.Z, Y: .071, Signal: v.Signal, SignalHorizontal: v.SignalHorizontal, BusStop: v.BusStop}
	if v.Y != nil {
		n.Y = *v.Y
	}
	return nil
}

type RoadEdge struct {
	From, To             int
	Length, Speed, Width float64
	Truck                bool
	Name                 string
	Way                  int64
	Oneway               bool
	Bus                  bool
}

func (e *RoadEdge) UnmarshalJSON(raw []byte) error {
	var v struct {
		From   int     `json:"from"`
		To     int     `json:"to"`
		Length float64 `json:"length"`
		Speed  float64 `json:"speed"`
		Width  float64 `json:"width"`
		Truck  bool    `json:"truck"`
		Name   string  `json:"name"`
		Way    int64   `json:"way"`
		Oneway bool    `json:"oneway"`
		Bus    *bool   `json:"bus"`
	}
	if err := json.Unmarshal(raw, &v); err != nil {
		return err
	}
	*e = RoadEdge{v.From, v.To, v.Length, v.Speed, v.Width, v.Truck, v.Name, v.Way, v.Oneway, v.Bus == nil || *v.Bus}
	return nil
}

